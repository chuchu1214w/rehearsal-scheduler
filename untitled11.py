def make_tasks(song_ids: Iterable[str]) -> List[Task]:
    tasks: List[Task] = []
    for song_id in sorted(song_ids):
        durations = SONG_SESSION_OVERRIDE.get(song_id, REQUIRED_DURATIONS[SONGS[song_id]["difficulty"]])
