def build_complete_model(data: InputData, tasks: Sequence[Task], candidates: Dict[str, List[Candidate]], *, windows_919=None, max_absent_ratio: float = 0.20) -> ModelBundle:
    zero = [task.task_id for task in tasks if not candidates[task.task_id]]
    if zero:
        raise ValueError("以下任务没有任何共同连续时段：" + "、".join(zero))

    model = cp_model.CpModel()
