def canonical_member(value: object) -> str:
    text = str(value or "").strip().replace("→", "").strip()
    aliases = {"ash": "Ash", "siri": "Siri", "mo": "Mo"}
    return aliases.get(text.lower(), text)


def to_date(value: object) -> Optional[date]:
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    parsed = pd.to_datetime(value, errors="coerce")
    if pd.isna(parsed):
        return None
    return parsed.date()


def normalize_slot_label(value: object) -> Optional[str]:
    if value is None:
        return None
    text = str(value).strip().replace("—", "–").replace("-", "–").replace("~", "–")
    nums = re.findall(r"(?<!\d)(\d{1,2})(?::(\d{2}))?", text)
    if len(nums) < 2:
        return None
    h1, m1 = int(nums[0][0]), int(nums[0][1] or 0)
    h2, m2 = int(nums[1][0]), int(nums[1][1] or 0)
    if m1 != 0 or m2 != 0:
        return None
    return f"{h1:02d}:00–{h2:02d}:00"


NORMALIZED_SLOT_TO_INDEX = {normalize_slot_label(label): i for i, label in enumerate(SLOT_LABELS)}


def coerce_binary(value: object, context: str, warnings: List[str]) -> int:
    if value in (1, True, "1", "✅", "🉑", "可"):
        return 1
    if value in (0, False, "0", "❌", "不可"):
        return 0
    if value is None or str(value).strip() == "":
        warnings.append(f"{context} 为空，已按 0（不可排练）处理。")
        return 0
    try:
        numeric = int(value)
        if numeric in (0, 1):
            return numeric
    except (TypeError, ValueError):
        pass
    raise ValueError(f"{context} 必须是 0/1，实际为：{value!r}")


def find_matrix_header(ws) -> Optional[Tuple[int, Dict[int, int]]]:
    max_row = min(ws.max_row or 0, 40)
    max_col = min(ws.max_column or 0, 40)
    for r in range(1, max_row + 1):
        values = [ws.cell(r, c).value for c in range(1, max_col + 1)]
        if not any(str(v or "").strip() == "日期" for v in values):
            continue
        slot_columns: Dict[int, int] = {}
        for c, value in enumerate(values, start=1):
            normalized = normalize_slot_label(value)
            if normalized in NORMALIZED_SLOT_TO_INDEX:
                slot_columns[NORMALIZED_SLOT_TO_INDEX[normalized]] = c
        if len(slot_columns) == H:
            return r, slot_columns
    return None


def extract_member_name(ws, sheet_name: str) -> str:
    for cell in (ws["A2"].value, ws["A1"].value):
        text = str(cell or "").strip()
        match = re.search(r"成员\s*[:：]\s*([^｜|]+)", text)
        if match:
            return canonical_member(match.group(1))
        if "｜" in text or "|" in text:
            first = re.split(r"[｜|]", text)[0].strip()
            if first and first not in {"全员共用", "排练软偏好"}:
                return canonical_member(first)
    for suffix in ("_有效时间矩阵", "_个人原始矩阵", "有效时间矩阵", "个人原始矩阵"):
        if sheet_name.endswith(suffix):
            prefix = sheet_name[: -len(suffix)].strip("_ ")
            if prefix:
                return canonical_member(prefix)
    return ""


def read_matrix_sheet(ws, label: str, warnings: List[str]) -> Dict[date, List[int]]:
    found = find_matrix_header(ws)
    if not found:
        raise ValueError(f"{label} 找不到完整的 14 个小时表头。")
    header_row, slot_columns = found
    date_col = next(
        c for c in range(1, (ws.max_column or 1) + 1)
        if str(ws.cell(header_row, c).value or "").strip() == "日期"
    )
    result: Dict[date, List[int]] = {}
    for r in range(header_row + 1, (ws.max_row or header_row) + 1):
        d = to_date(ws.cell(r, date_col).value)
        if d is None:
            continue
        row = [0] * H
        for h, c in slot_columns.items():
            row[h] = coerce_binary(ws.cell(r, c).value, f"{label} {d} {SLOT_LABELS[h]}", warnings)
        result[d] = row
    if not result:
        raise ValueError(f"{label} 没有读到任何日期数据。")
    return result


def parse_hour_range_to_slots(value: object) -> List[int]:
    text = str(value or "").replace("—", "–").replace("-", "–").replace("~", "–")
    nums = re.findall(r"(?<!\d)(\d{1,2})(?::(\d{2}))?", text)
    if len(nums) < 2:
        return []
    start_h, start_m = int(nums[0][0]), int(nums[0][1] or 0)
    end_h, end_m = int(nums[1][0]), int(nums[1][1] or 0)
    if start_m != 0 or end_m != 0 or start_h not in SLOT_START_HOURS:
        return []
    start_idx = SLOT_START_HOURS.index(start_h)
    end_idx = next((i for i in range(start_idx + 1, len(BOUNDARY_HOURS)) if BOUNDARY_HOURS[i] == end_h), None)
    if end_idx is None:
        return []
    return list(range(start_idx, end_idx))


def read_soft_preferences(ws, warnings: List[str]) -> Set[Tuple[str, date, int]]:
    result: Set[Tuple[str, date, int]] = set()
    header_row = None
    headers: Dict[str, int] = {}
    for r in range(1, min(ws.max_row or 0, 30) + 1):
        row_headers = {str(ws.cell(r, c).value or "").strip(): c for c in range(1, (ws.max_column or 0) + 1)}
        if {"成员", "日期", "可用时段"}.issubset(row_headers):
            header_row, headers = r, row_headers
            break
    if not header_row:
        return result
    for r in range(header_row + 1, (ws.max_row or header_row) + 1):
        member = canonical_member(ws.cell(r, headers["成员"]).value)
        d = to_date(ws.cell(r, headers["日期"]).value)
        slots = parse_hour_range_to_slots(ws.cell(r, headers["可用时段"]).value)
        if not member or not d:
            continue
        if not slots:
            warnings.append(f"排练偏好第 {r} 行的时段无法识别，已跳过。")
            continue
        result.update((member, d, h) for h in slots)
    return result


