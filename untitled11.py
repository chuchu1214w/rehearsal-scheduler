def split_active_songs(data: InputData) -> Tuple[List[str], List[dict]]:
    loaded = set(data.availability)
    active: List[str] = []
    pending: List[dict] = []
    for song_id, song in SONGS.items():
        missing = [m for m in song["members"] if m not in loaded]
        if missing:
            pending.append({
                "曲目ID": song_id,
                "曲目": song["name"],
                "难度": song["difficulty"],
                "全体成员": "、".join(song["members"]),
                "缺少时间表": "、".join(missing),
                "状态": "等待时间表",
            })
        else:
            active.append(song_id)
    if pending and MISSING_MEMBER_POLICY == "strict":
        missing_all = sorted({m for row in pending for m in row["缺少时间表"].split("、")}, key=lambda x: MEMBER_ORDER.index(x))
        raise ValueError("strict 模式：尚缺成员时间表：" + "、".join(missing_all))
    if MISSING_MEMBER_POLICY not in {"strict", "provisional"}:
        raise ValueError("MISSING_MEMBER_POLICY 只能是 'strict' 或 'provisional'。")
    return active, pending


def candidate_is_available(data: InputData, song_id: str, d: date, start: int, duration: int) -> bool:
    hours = range(start, start + duration)
    if not all(data.global_allowed[d][h] for h in hours):
        return False
    return all(
        all(data.availability[member][d][h] for h in hours)
        for member in SONGS[song_id]["members"]
    )


def build_candidate_lists(data: InputData, tasks: Sequence[Task], strict: bool = True) -> Dict[str, List[Candidate]]:
    result: Dict[str, List[Candidate]] = {}
    for task in tasks:
        choices: List[Candidate] = []
        for di, d in enumerate(data.dates):
            for start in range(0, H - task.duration + 1):
                if strict:
                    allowed = candidate_is_available(data, task.song_id, d, start, task.duration)
                else:
                    allowed = all(data.global_allowed[d][h] for h in range(start, start + task.duration))
                if allowed:
                    choices.append(Candidate(di, start, task.duration))
                elif strict:
                    # 近似解：允许恰好缺席一名成员（全局时间必须满足）
                    global_ok = all(data.global_allowed[d][h] for h in range(start, start + task.duration))
                    if global_ok:
                        for absent_m in SONGS[task.song_id]["members"]:
                            other_m = [m for m in SONGS[task.song_id]["members"] if m != absent_m]
                            if other_m and all(
                                data.availability[m][d][h]
                                for m in other_m
                                if m in data.availability and d in data.availability[m]
                                for h in range(start, start + task.duration)
                            ):
                                choices.append(Candidate(di, start, task.duration, absent_m))
        result[task.task_id] = choices
    return result


