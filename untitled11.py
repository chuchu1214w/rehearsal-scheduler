def load_availability(input_path: str | Path) -> InputData:
    warnings: List[str] = []
    availability: Dict[str, Dict[date, List[int]]] = {}
    public_rules: Dict[date, List[int]] = {}
    soft_avoid: Set[Tuple[str, date, int]] = set()
    paths = workbook_paths(input_path)

    for path in paths:
        wb = load_workbook(path, data_only=True, read_only=False)
        effective_names = [name for name in wb.sheetnames if is_effective_sheet_name(name)]
        candidate_names = effective_names
        if not candidate_names:
            candidate_names = [
                name for name in wb.sheetnames
                if name not in {"公共限制", "排练偏好"} and find_matrix_header(wb[name])
            ]
            if candidate_names:
                warnings.append(f"{path.name} 没有‘有效时间矩阵’，已改读其中可识别的个人矩阵。")

        for name in candidate_names:
            ws = wb[name]
            member = extract_member_name(ws, name)
            if not member:
                warnings.append(f"{path.name}/{name} 无法识别成员姓名，已跳过。")
                continue
            matrix = read_matrix_sheet(ws, f"{path.name}/{name}", warnings)
            if member in availability and availability[member] != matrix:
                raise ValueError(f"成员 {member} 在多个文件/工作表中出现，且矩阵内容不一致。")
            availability[member] = matrix

        if "公共限制" in wb.sheetnames:
            rules = read_matrix_sheet(wb["公共限制"], f"{path.name}/公共限制", warnings)
            for d, row in rules.items():
                if d in public_rules and public_rules[d] != row:
                    raise ValueError(f"日期 {d} 的公共限制在多个文件中不一致。")
                public_rules[d] = row
        if "排练偏好" in wb.sheetnames:
            soft_avoid |= read_soft_preferences(wb["排练偏好"], warnings)

    if not availability:
        raise ValueError("没有读到任何成员的时间矩阵。请确认工作表包含‘日期’和 14 个小时列。")

    all_dates = sorted({d for matrix in availability.values() for d in matrix})
    dates = [d for d in all_dates if EARLIEST_REHEARSAL_DATE <= d <= LAST_REHEARSAL_DATE and d < PERFORMANCE_DATE]
    if not dates:
        raise ValueError("输入矩阵中没有位于正式排练区间内的日期。")

    global_allowed: Dict[date, List[int]] = {}
    for d in dates:
        transit = [1] * H
        if d.weekday() >= 5:  # 周六、周日必须在 00:00 前结束
            transit[-1] = 0
        if d in public_rules:
            transit = [a * b for a, b in zip(transit, public_rules[d])]
        global_allowed[d] = transit

    # 即使输入的是个人原始矩阵，也在这里统一套用公共末班车限制。
    for member, matrix in availability.items():
        for d in dates:
            if d not in matrix:
                warnings.append(f"成员 {member} 缺少 {d} 这一行，已按全天不可用处理。")
                matrix[d] = [0] * H
            matrix[d] = [a * b for a, b in zip(matrix[d], global_allowed[d])]

    loaded = set(availability)
    unknown_names = sorted(loaded - set(MEMBER_ORDER))
    if unknown_names:
        warnings.append("读到未在 14 人名单中的成员：" + "、".join(unknown_names))

    return InputData(
        availability=availability,
        global_allowed=global_allowed,
        soft_avoid=soft_avoid,
        dates=dates,
        warnings=list(dict.fromkeys(warnings)),
        source_files=[str(p) for p in paths],
    )


