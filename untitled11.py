@dataclass
class AdjustmentResult:
    feasible: bool
    status: str
    exact: bool
    affected_members: int
    changed_hours: int
    changes: List[dict]
    relaxed_schedule: List[dict]


def solve_minimum_adjustment(data: InputData, tasks: Sequence[Task], time_limit: float = 60.0) -> AdjustmentResult:
    # 允许使用个人矩阵中原本为 0 的格子，但仍遵守公共末班车、人员不重叠和单日硬上限。
    candidates = build_candidate_lists(data, tasks, strict=False)
    if any(not candidates[t.task_id] for t in tasks):
        return AdjustmentResult(False, "公共时间范围本身不足", False, 0, 0, [], [])

    model = cp_model.CpModel()
    x: Dict[Tuple[str, int], cp_model.IntVar] = {}
    change: Dict[Tuple[str, int, int], cp_model.IntVar] = {}
    for task in tasks:
        vars_for_task = []
        for ci, c in enumerate(candidates[task.task_id]):
            var = model.NewBoolVar(f"relax_x_{task.task_id}_{ci}")
            x[(task.task_id, ci)] = var
            vars_for_task.append(var)
            d = data.dates[c.date_idx]
            for member in SONGS[task.song_id]["members"]:
                for h in c.hours:
                    if data.availability[member][d][h] == 0:
                        key = (member, c.date_idx, h)
                        if key not in change:
                            change[key] = model.NewBoolVar(f"open_{member}_{c.date_idx}_{h}")
                        model.Add(var <= change[key])
        model.Add(sum(vars_for_task) == 1)

    add_partial_hard_constraints(model, data, tasks, candidates, x)
    member_changes: Dict[str, List[cp_model.IntVar]] = defaultdict(list)
    for (member, _di, _h), var in change.items():
        member_changes[member].append(var)
    affected: Dict[str, cp_model.IntVar] = {}
    for member, vars_for_member in member_changes.items():
        flag = model.NewBoolVar(f"affected_{member}")
        model.AddMaxEquality(flag, vars_for_member)
        affected[member] = flag

    affected_expr = sum(affected.values())
    changed_expr = sum(change.values())
    model.Minimize(affected_expr)
    solver1 = new_solver(time_limit)
    status1 = solver1.Solve(model)
    if status1 not in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        return AdjustmentResult(False, solver1.StatusName(status1), False, 0, 0, [], [])
    best_affected = int(round(solver1.ObjectiveValue()))
    model.Add(affected_expr == best_affected)

    model.Minimize(changed_expr)
    solver2 = new_solver(time_limit)
    status2 = solver2.Solve(model)
    if status2 not in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        return AdjustmentResult(False, solver2.StatusName(status2), False, 0, 0, [], [])
    best_changed = int(round(solver2.ObjectiveValue()))
    exact = status1 == cp_model.OPTIMAL and status2 == cp_model.OPTIMAL

    changes = []
    for (member, di, h), var in change.items():
        if solver2.Value(var):
            d = data.dates[di]
            changes.append({
                "成员": member,
                "日期": d,
                "星期": WEEKDAY_ZH[d.weekday()],
                "需额外开放小时格": SLOT_LABELS[h],
                "调整小时数": 1,
            })
    changes.sort(key=lambda r: (MEMBER_ORDER.index(r["成员"]) if r["成员"] in MEMBER_ORDER else 999, r["日期"], r["需额外开放小时格"]))

    relaxed_schedule = []
    for task in tasks:
        for ci, c in enumerate(candidates[task.task_id]):
            if solver2.Value(x[(task.task_id, ci)]):
                d = data.dates[c.date_idx]
                _, _, block = time_text(c.start, c.duration)
                relaxed_schedule.append({
                    "任务ID": task.task_id,
                    "曲目ID": task.song_id,
                    "曲目": SONGS[task.song_id]["name"],
                    "日期": d,
                    "星期": WEEKDAY_ZH[d.weekday()],
                    "建议时段": block,
                    "时长(小时)": c.duration,
                    "成员": "、".join(SONGS[task.song_id]["members"]),
                })
                break
    relaxed_schedule.sort(key=lambda r: (r["日期"], r["建议时段"], r["曲目ID"]))
    return AdjustmentResult(True, solver2.StatusName(status2), exact, best_affected, best_changed, changes, relaxed_schedule)


